import { test, expect } from '@playwright/test';
import { snap, go } from './helpers';
test.use({ deviceScaleFactor: 0.5 });

test('três encomendas e retorno ao elevador, dificuldade normal', async ({ page }) => {
  test.setTimeout(600000);
  await page.setViewportSize({ width: 480, height: 270 });
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/');
  await page.locator('#quality').selectOption('low');
  await page.getByTestId('start').click();
  await expect.poll(async () => (await snap(page)).time).toBeGreaterThan(0.1);
  await page.keyboard.press('e');
  await expect.poll(async () => (await snap(page)).held).toBe(true);
  await go(page, 0, -6);
  await go(page, -14.7, -6);
  await go(page, -14.7, 6);
  await go(page, -10.5, 6);
  await page.keyboard.press('e');
  await expect.poll(async () => (await snap(page)).delivered).toBe(1);
  await go(page, -14.7, 6);
  await go(page, -14.7, -6);
  await go(page, 0, -6);
  await go(page, 0, -12);
  await page.keyboard.press('e');
  await expect.poll(async () => (await snap(page)).held).toBe(true);
  await go(page, 0, -6);
  await go(page, -14.7, -6);
  await go(page, -14.7, 5.1);
  await go(page, 0, 5.1);
  await go(page, 0, 6.4);
  await page.keyboard.press('e');
  await expect.poll(async () => (await snap(page)).delivered).toBe(2);
  await page.screenshot({ path: 'evidence/marco2-segunda.png' });
  await go(page, 0, 5.1);
  await go(page, 14.7, 5.1);
  await go(page, 14.7, -6.8);
  await go(page, 0, -6.8);
  await go(page, 0, -6);
  await go(page, 0, -12);
  await page.keyboard.press('e');
  await expect.poll(async () => (await snap(page)).held).toBe(true);
  await go(page, 0, -6.8);
  await go(page, 14.7, -6.8);
  await go(page, 14.7, -6);
  await go(page, 14.7, 5.1);
  await go(page, 10.5, 5.1);
  await go(page, 10.5, 6.4);
  await page.keyboard.press('e');
  await expect.poll(async () => (await snap(page)).delivered).toBe(3);
  // Empty-handed escape can use running without agitating a parcel.
  await page.keyboard.down('Shift');
  await go(page, 10.5, 5.1);
  await go(page, 14.7, 5.1);
  await go(page, 14.7, -6.8);
  await go(page, 0, -6.8);
  await go(page, 0, -6);
  await go(page, 0, -12);
  await page.keyboard.up('Shift');
  await page.keyboard.press('e');
  await expect(page.locator('#ui')).toHaveAttribute('data-phase', 'WON');
  await page.screenshot({ path: 'evidence/marco2-vitoria.png' });
  expect(errors).toEqual([]);
});
